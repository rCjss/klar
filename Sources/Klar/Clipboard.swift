import AppKit
import Combine

final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    @Published private(set) var items: [ClipItem] = []
    private let debouncer = Debouncer()

    private init() {
        items = Storage.load("clipboard.json") ?? []
    }

    /// Angepinnte zuerst, dann nach Zeit.
    var ordered: [ClipItem] {
        items.sorted { a, b in
            if a.pinned != b.pinned { return a.pinned }
            return a.createdAt > b.createdAt
        }
    }

    /// Rückt einen vorhandenen Eintrag wie frisch kopiert an den Anfang.
    func touch(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }), idx > 0 else { return }
        let item = items.remove(at: idx)
        items.insert(item, at: 0)
        persist()
    }

    func add(_ new: ClipItem) {
        var item = new
        if item.kind == .text, let text = item.text,
           let existing = items.first(where: { $0.kind == .text && $0.text == text }) {
            item.id = existing.id
            item.pinned = existing.pinned
            items.removeAll { $0.id == existing.id }
        }
        items.insert(item, at: 0)
        trim()
        persist()
    }

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        persist()
    }

    func remove(_ id: UUID) {
        if let item = items.first(where: { $0.id == id }), let file = item.imageFile {
            try? FileManager.default.removeItem(at: Storage.images.appendingPathComponent(file))
        }
        items.removeAll { $0.id == id }
        persist()
    }

    func clearUnpinned() {
        for item in items where !item.pinned {
            if let file = item.imageFile {
                try? FileManager.default.removeItem(at: Storage.images.appendingPathComponent(file))
            }
        }
        items.removeAll { !$0.pinned }
        persist()
    }

    private func trim() {
        let limit = max(20, Settings.shared.historyLimit)
        var count = 0
        var keep: [ClipItem] = []
        for item in items {
            if item.pinned { keep.append(item); continue }
            if count < limit { keep.append(item); count += 1 }
            else if let file = item.imageFile {
                try? FileManager.default.removeItem(at: Storage.images.appendingPathComponent(file))
            }
        }
        items = keep
    }

    private func persist() {
        let snapshot = items
        debouncer.call { Storage.save(snapshot, as: "clipboard.json") }
    }
}

/// Beobachtet die System-Zwischenablage per changeCount-Polling.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()
    private var timer: Timer?
    private var lastCount: Int
    private var ownCount: Int = -1
    private let pb = NSPasteboard.general

    private init() {
        lastCount = pb.changeCount
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(timer!, forMode: .common)
    }

    static let sensitiveSources = [
        "com.apple.keychainaccess", "com.apple.passwords", "com.1password", "com.agilebits",
        "com.bitwarden", "org.keepassxc", "com.strongbox", "in.sinew.enpass", "com.dashlane",
        "com.lastpass", "com.nordpass", "com.proton.pass", "com.keepersecurity",
    ]

    func noteOwnChange() {
        ownCount = pb.changeCount
        lastCount = ownCount
    }

    private func check() {
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard count != ownCount else { return }

        let types = pb.types ?? []
        // Passwortmanager und transiente Inhalte respektieren
        if types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            || types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            || types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")) {
            return
        }
        let app = NSWorkspace.shared.frontmostApplication
        // Kopien aus Passwortmanagern und der Schlüsselbundverwaltung landen nie im Verlauf.
        if let bundle = app?.bundleIdentifier?.lowercased(),
           Self.sensitiveSources.contains(where: { bundle.hasPrefix($0) }) {
            return
        }
        let source = app?.localizedName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            ClipboardStore.shared.add(ClipItem(kind: .files, files: urls.map { $0.path }, sourceApp: source))
            return
        }
        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            ClipboardStore.shared.add(ClipItem(kind: .text, text: text, sourceApp: source))
            return
        }
        if let image = NSImage(pasteboard: pb), let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            let file = Storage.images.appendingPathComponent(name)
            try? png.write(to: file)
            try? FileManager.default.setAttributes(Storage.fileAttrs, ofItemAtPath: file.path)
            ClipboardStore.shared.add(ClipItem(kind: .image, imageFile: name, sourceApp: source))
        }
    }
}
